export const GLOSSARY_TR: ReadonlyMap<string, string> = new Map(
  RAW.trim()
    .split('\n')
    .map((line) => {
      const i = line.indexOf(': ')
      return [line.slice(0, i).trim(), line.slice(i + 2).trim()] as const
    }),
)

/** Normalised lookup key: lower case, straight apostrophes, no surrounding punctuation. */
export function glossKey(word: string): string {
  return word
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/^[^a-z0-9]+|[^a-z0-9]+$/g, '')
}

export function glossTr(word: string): string | undefined {
  return GLOSSARY_TR.get(glossKey(word))
}
